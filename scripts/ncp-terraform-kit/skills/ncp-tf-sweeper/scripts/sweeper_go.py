"""The Go the sweeper render writes: the core, its entry point, and their tests.

The core takes an injected client, so its selection, its order and its
list-then-delete flow are tested against a fake with no account. The agent
writes the one file that reaches the NCP: `adapter.go`, which defines
`NewClient`. The record is written as JSON, which every YAML reader reads, so
the core needs nothing outside the Go standard library.
"""

