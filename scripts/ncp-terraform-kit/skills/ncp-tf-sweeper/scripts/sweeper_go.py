CORE = (
    HEADER
    + r"""package main

import (
	"context"
	"errors"
	"fmt"
	"sort"
	"strings"
)

// kitPrefix opens the name of every resource a run creates.
const kitPrefix = "tfkit"

// ErrNotFound is what adapter.go's List wraps when the NCP answers that the
// scope does not exist.
var ErrNotFound = errors.New("the scope does not exist")

// Param is one required parameter of a type's list operation.
type Param struct {
	Name string
	// Template holds {name} placeholders, each read from TFKIT_VAR_<NAME>.
	// With Env set, it starts with the account scope, and Env's value fills
	// the first placeholder.
	Template string
	// Env holds the whole value, or the value of the account scope in Template.
	Env string
	// ScopeType is a planned type: the value is each resource of it that the
	// sweep found for the run, and the supplied value when it is set.
	ScopeType string
	// Pattern is the parameter's document pattern. A supplied value that does
	// not match it addresses nothing that the API lists.
	Pattern string
}

// Type is one planned resource type, as the sweep plan derived it.
type Type struct {
	Name         string
	ListMethod   string
	ListPath     string
	DeleteMethod string
	DeletePath   string
	Params       []Param
	Separator    string
	// NamePrefixes are the texts that the type's cases write before the kit
	// prefix, because the API requires them, as GCP requires `custom.`.
	NamePrefixes []string
	RunLabel     string
	// RunFields are the fields, other than the name, that carry the run id.
	RunFields []string
	// ByParent is the planned type that the resources are listed under. A
	// resource carries no run id of its own and is the run's when its parent is.
	ByParent string
	// DeletedField, a dotted path, holds DeletedValue on a resource that the
	// NCP deleted and still lists for a while. Such a resource is gone, and the
	// NCP refuses its delete.
	DeletedField string
	DeletedValue string
	CannotList   string
	CannotDelete string
}

// ListedFields are the fields of a listed resource that the core reads.
// adapter.go returns the value of each in Resource.Fields.
func (t Type) ListedFields() []string {
	if t.DeletedField == "" {
		return t.RunFields
	}
	return append(append([]string{}, t.RunFields...), t.DeletedField)
}

// Resource is one resource as the NCP lists it. Fields holds the value of
// each of the type's ListedFields, as the NCP returns it: a value that is not a
// string, as its JSON text.
type Resource struct {
	Name   string            `json:"name"`
	Labels map[string]string `json:"labels,omitempty"`
	Fields map[string]string `json:"fields,omitempty"`
}

// Client lists and deletes through the NCP's API. adapter.go implements it.
// List wraps ErrNotFound when the NCP answers that the scope does not exist.
// Delete returns when the NCP reports the resource gone or returns an error,
// so the next delete in the order does not meet a resource still in use.
type Client interface {
	List(ctx context.Context, t Type, scope map[string]string) ([]Resource, error)
	Delete(ctx context.Context, t Type, scope map[string]string, r Resource) error
}

// Found is a resource of the run.
type Found struct {
	Type    string            `json:"type"`
	Name    string            `json:"name"`
	Labels  map[string]string `json:"labels,omitempty"`
	Fields  map[string]string `json:"fields,omitempty"`
	Scope   map[string]string `json:"scope,omitempty"`
	Matched string            `json:"matched"`
}

// Failed is a resource whose delete the NCP refused.
type Failed struct {
	Type  string `json:"type"`
	Name  string `json:"name"`
	Error string `json:"error"`
}

// Reason says why a type was not listed or is never deleted.
type Reason struct {
	Type   string `json:"type"`
	Reason string `json:"reason"`
}

// Record is the sweep record the sweeper writes on stdout.
type Record struct {
	Kind         string                         `json:"kind"`
	RunID        string                         `json:"run_id"`
	Scope        map[string][]map[string]string `json:"scope"`
	Found        []Found                        `json:"found"`
	Deleted      []Found                        `json:"deleted"`
	CannotList   []Reason                       `json:"cannot_list"`
	CannotDelete []Reason                       `json:"cannot_delete"`
	Removed      []Found                        `json:"removed,omitempty"`
	Failed       []Failed                       `json:"failed,omitempty"`
	Left         []Found                        `json:"left,omitempty"`
}

// list finds the run's resources. A scope type is listed before the types
// listed under it, so the plan, which is in deletion order, is walked back.
func list(ctx context.Context, client Client, plan []Type, runID string, getenv func(string) string) Record {
	record := Record{Kind: "sweep", RunID: runID, Scope: map[string][]map[string]string{},
		Found: []Found{}, Deleted: []Found{}, CannotList: []Reason{}, CannotDelete: []Reason{}}
	for i := len(plan) - 1; i >= 0; i-- {
		t := plan[i]
		if t.CannotDelete != "" {
			record.CannotDelete = append(record.CannotDelete, Reason{t.Name, t.CannotDelete})
		}
		if t.CannotList != "" {
			record.CannotList = append(record.CannotList, Reason{t.Name, t.CannotList})
			continue
		}
		// A deleted resource that the NCP still lists is a scope: a leak under
		// it is listed, not unknown.
		listed, err := scopes(t, runID, append(append([]Found{}, record.Found...), record.Deleted...), getenv)
		if err != nil {
			record.CannotList = append(record.CannotList, Reason{t.Name, err.Error()})
			if len(listed) == 0 {
				continue
			}
		}
		record.Scope[t.Name] = listed
		for _, scope := range listed {
			resources, err := client.List(ctx, t, scope)
			if errors.Is(err, ErrNotFound) && holdsDeleted(scope, record.Deleted) {
				// The NCP states that nothing is under a resource that it deleted.
				continue
			}
			if err != nil {
				record.CannotList = append(record.CannotList,
					Reason{t.Name, fmt.Sprintf("the list in %v failed: %v", scope, err)})
				continue
			}
			for _, r := range resources {
				by, ok := matches(t, r, runID)
				if !ok {
					continue
				}
				f := Found{Type: t.Name, Name: r.Name, Labels: r.Labels, Fields: r.Fields, Scope: scope, Matched: by}
				if deleted(t, r) {
					record.Deleted = append(record.Deleted, f)
				} else {
					record.Found = append(record.Found, f)
				}
			}
		}
	}
	sort.SliceStable(record.CannotDelete, func(i, j int) bool { return record.CannotDelete[i].Type < record.CannotDelete[j].Type })
	return record
}

// holdsDeleted says whether a scope is a resource that the NCP keeps as deleted.
func holdsDeleted(scope map[string]string, deleted []Found) bool {
	for _, value := range scope {
		for _, f := range deleted {
			if value == f.Name {
				return true
			}
		}
	}
	return false
}

// sweep deletes what the operator approved and what is still there, in the
// plan's order, then lists again and records what is left. A resource whose
// delete returned is not left: Delete returns once the NCP's read reports it
// gone, and a list can return it for a while after that.
func sweep(ctx context.Context, client Client, plan []Type, runID string, getenv func(string) string, approved Record) Record {
	record := list(ctx, client, plan, runID, getenv)
	allowed := map[string]bool{}
	for _, f := range approved.Found {
		if approved.RunID == runID {
			allowed[approvalKey(f)] = true
		}
	}
	for _, t := range plan {
		if t.CannotDelete != "" {
			continue
		}
		for _, f := range record.Found {
			if f.Type != t.Name || !allowed[approvalKey(f)] {
				continue
			}
			if err := client.Delete(ctx, t, f.Scope, Resource{Name: f.Name, Labels: f.Labels, Fields: f.Fields}); err != nil {
				record.Failed = append(record.Failed, Failed{f.Type, f.Name, err.Error()})
				continue
			}
			record.Removed = append(record.Removed, f)
		}
	}
	gone := map[string]bool{}
	for _, f := range record.Removed {
		gone[approvalKey(f)] = true
	}
	for _, f := range list(ctx, client, plan, runID, getenv).Found {
		if !gone[approvalKey(f)] {
			record.Left = append(record.Left, f)
		}
	}
	return record
}

// approvalKey names one resource in the scope it was listed in. Two scopes can
// each hold a resource of one name, and the operator approved only the one
// that the record shows.
func approvalKey(f Found) string {
	names := make([]string, 0, len(f.Scope))
	for name := range f.Scope {
		names = append(names, name)
	}
	sort.Strings(names)
	parts := []string{f.Type, f.Name}
	for _, name := range names {
		parts = append(parts, name+"="+f.Scope[name])
	}
	return strings.Join(parts, "\x00")
}

// unlisted counts the types that the plan can list and that this sweep did
// not: a value was unset or a list failed. A leak of such a type is unknown.
func unlisted(plan []Type, record Record) int {
	planned := map[string]bool{}
	for _, t := range plan {
		if t.CannotList != "" {
			planned[t.Name] = true
		}
	}
	count := 0
	for _, reason := range record.CannotList {
		if !planned[reason.Type] {
			count++
		}
	}
	return count
}
"""
)

MAIN = (
    HEADER
    + r"""package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"regexp"
)

// runIDForm is the form of the id the runner writes: a fixed length. A type
// whose names have no separator after the run id is selected by prefix, and a
// shorter id would select the resources of other runs.
var runIDForm = regexp.MustCompile(`^tfkit[0-9a-z]{8}$`)

// exitUnlisted is the status of a sweep that finished and could not list a
// type that the plan can list. Its record is complete for every other type.
const exitUnlisted = 3

func main() {
	os.Exit(run(context.Background(), os.Args[1:], os.Stdout, os.Stderr, os.Getenv, NewClient))
}

func run(ctx context.Context, args []string, stdout, stderr io.Writer, getenv func(string) string,
	newClient func(context.Context) (Client, error)) int {
	flags := flag.NewFlagSet("sweep", flag.ContinueOnError)
	flags.SetOutput(stderr)
	runID := flags.String("run-id", "", "the run whose resources to find; required")
	approvedPath := flags.String("delete", "", "the sweep record the operator approved; without it, nothing is deleted")
	if err := flags.Parse(args); err != nil {
		return 2
	}
	if !runIDForm.MatchString(*runID) {
		_, _ = fmt.Fprintln(stderr, "sweep: refusing to start without a run id (--run-id). "+
			"The kit prefix alone would select the resources of every run in the account.")
		return 2
	}
	var approved Record
	if *approvedPath != "" {
		text, err := os.ReadFile(*approvedPath)
		if err == nil {
			err = json.Unmarshal(text, &approved)
		}
		if err != nil || approved.Kind != "sweep" || approved.RunID != *runID {
			_, _ = fmt.Fprintf(stderr, "sweep: %s is not an approved sweep record of run %s\n", *approvedPath, *runID)
			return 2
		}
	}
	client, err := newClient(ctx)
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "sweep: %v\n", err)
		return 1
	}
	var record Record
	if *approvedPath == "" {
		record = list(ctx, client, plan, *runID, getenv)
	} else {
		record = sweep(ctx, client, plan, *runID, getenv, approved)
	}
	encoder := json.NewEncoder(stdout)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(record); err != nil {
		_, _ = fmt.Fprintf(stderr, "sweep: %v\n", err)
		return 1
	}
	_, _ = fmt.Fprintf(stderr, "sweep: %d found, %d types not listed, %d removed, %d failed, %d left\n",
		len(record.Found), len(record.CannotList), len(record.Removed), len(record.Failed), len(record.Left))
	return status(plan, record)
}

// status is 1 when a delete failed or a resource is left, and exitUnlisted
// when the sweep could not list a type that the plan can list.
func status(plan []Type, record Record) int {
	if len(record.Failed) > 0 || len(record.Left) > 0 {
		return 1
	}
	if unlisted(plan, record) > 0 {
		return exitUnlisted
	}
	return 0
}
"""
)


def go_string(value: str) -> str:
    return json.dumps(value)


def plan_source(types: list[Any]) -> str:
    """`plan.go`: the sweep plan as Go values, in deletion order."""
    rows = []
    for t in types:
        fields = [f"Name: {go_string(t.terraform_type)}"]
        for name, value in (
            ("ListMethod", t.list_method),
            ("ListPath", t.list_path),
            ("DeleteMethod", t.delete_method),
            ("DeletePath", t.delete_path),
        ):
            if value:
                fields.append(f"{name}: {go_string(value)}")
        if t.params:
            params = ", ".join(
                "{"
                + ", ".join(
                    f"{key}: {go_string(value)}"
                    for key, value in (
                        ("Name", p.name),
                        ("Template", p.template),
                        ("Env", p.env),
                        ("ScopeType", p.scope_type),
                        ("Pattern", p.pattern),
                    )
                    if value
                )
                + "}"
                for p in t.params
            )
            fields.append(f"Params: []Param{{{params}}}")
        fields.append(f"Separator: {go_string(t.separator)}")
        if t.name_prefixes:
            fields.append("NamePrefixes: []string{" + ", ".join(go_string(p) for p in t.name_prefixes) + "}")
        if t.run_fields:
            fields.append("RunFields: []string{" + ", ".join(go_string(f) for f, _ in t.run_fields) + "}")
        for name, value in (
            ("RunLabel", t.run_label),
            ("ByParent", t.by_parent),
            ("DeletedField", t.deleted_field),
            ("DeletedValue", t.deleted_value),
            ("CannotList", t.cannot_list),
            ("CannotDelete", t.cannot_delete),
        ):
            if value:
                fields.append(f"{name}: {go_string(value)}")
        rows.append("\t{" + ", ".join(fields) + "},\n")
    return (
        HEADER + "package main\n\n"
        "// plan is the sweep plan in deletion order: a type is deleted before each\n"
        "// type that it uses. sweep.yaml holds the same facts with their sources.\n"
        "var plan = []Type{\n" + "".join(rows) + "}\n"
    )


def files(types: list[Any]) -> dict[str, str]:
    """Every file the render writes. adapter.go is not one: the agent writes it."""
    return {
        "plan.go": plan_source(types),
        "sweeper.go": CORE,
        "select.go": HEADER + SELECT,
        "main.go": MAIN,
        "sweeper_test.go": HEADER + TESTS,
        "select_test.go": HEADER + SELECT_TESTS,
        "live_check_test.go": HEADER + LIVE_CHECK,
        "lagging_list_test.go": HEADER + LAGGING_TESTS,
    }
